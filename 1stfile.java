public class Main {
    public static void main(String[] args) {

        int number = 10;

        if (number % 2 == 0) {
            System.out.println("Even Number");
        } else {
            System.out.println("Odd Number");
        }

        for (int i = 1; i <= 5; i++) {
            System.out.println("Count: " + i);
        }
    }
}
